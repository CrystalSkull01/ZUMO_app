CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE zoo_map (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    map_key VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(160) NOT NULL,
    description TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE map_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zoo_map_id BIGINT NOT NULL REFERENCES zoo_map(id),
    version_label VARCHAR(80) NOT NULL,
    source_description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (zoo_map_id, version_label)
);

CREATE TABLE species (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scientific_name VARCHAR(200),
    classification VARCHAR(120),
    habitat TEXT,
    diet TEXT,
    native_range TEXT,
    conservation_status VARCHAR(120),
    verification_status VARCHAR(24) NOT NULL DEFAULT 'UNVERIFIED'
        CHECK (verification_status IN ('UNVERIFIED', 'PENDING_REVIEW', 'VERIFIED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE animal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    species_id BIGINT REFERENCES species(id),
    common_name VARCHAR(200) NOT NULL,
    description TEXT,
    verification_status VARCHAR(24) NOT NULL DEFAULT 'UNVERIFIED'
        CHECK (verification_status IN ('UNVERIFIED', 'PENDING_REVIEW', 'VERIFIED')),
    discoverable BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE map_feature (
    id VARCHAR(80) PRIMARY KEY,
    map_version_id BIGINT NOT NULL REFERENCES map_version(id),
    animal_id BIGINT REFERENCES animal(id),
    feature_type VARCHAR(32) NOT NULL
        CHECK (feature_type IN ('ANIMAL_LOCATION', 'FACILITY', 'LANDMARK', 'RECORDED_ROUTE', 'PATH', 'ENCLOSURE')),
    name VARCHAR(200) NOT NULL,
    geometry geometry(Geometry, 4326) NOT NULL,
    verification_status VARCHAR(24) NOT NULL DEFAULT 'UNVERIFIED'
        CHECK (verification_status IN ('UNVERIFIED', 'PENDING_REVIEW', 'VERIFIED')),
    name_verified BOOLEAN NOT NULL DEFAULT FALSE,
    needs_review BOOLEAN NOT NULL DEFAULT FALSE,
    review_note TEXT,
    source_name VARCHAR(240),
    source_record_id VARCHAR(120),
    source_recorded_at TIMESTAMPTZ,
    properties JSONB NOT NULL DEFAULT '{}'::JSONB,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT map_feature_geometry_srid CHECK (ST_SRID(geometry) = 4326),
    CONSTRAINT map_feature_geometry_type CHECK (
        (feature_type IN ('ANIMAL_LOCATION', 'FACILITY', 'LANDMARK') AND GeometryType(geometry) = 'POINT')
        OR (feature_type IN ('RECORDED_ROUTE', 'PATH') AND GeometryType(geometry) IN ('LINESTRING', 'MULTILINESTRING'))
        OR (feature_type = 'ENCLOSURE' AND GeometryType(geometry) IN ('POLYGON', 'MULTIPOLYGON'))
    ),
    CONSTRAINT map_feature_animal_link CHECK (
        animal_id IS NULL OR feature_type = 'ANIMAL_LOCATION'
    )
);

CREATE INDEX map_feature_geometry_gix ON map_feature USING GIST (geometry);
CREATE INDEX map_feature_type_active_idx ON map_feature (feature_type, active);
CREATE INDEX map_feature_version_idx ON map_feature (map_version_id);
CREATE INDEX map_feature_review_idx ON map_feature (needs_review, verification_status);

CREATE TABLE animal_image (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id BIGINT NOT NULL REFERENCES animal(id) ON DELETE CASCADE,
    image_url TEXT NOT NULL,
    alt_text VARCHAR(240),
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE animal_information_verification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id BIGINT NOT NULL REFERENCES animal(id) ON DELETE CASCADE,
    field_name VARCHAR(120) NOT NULL,
    source_name VARCHAR(240) NOT NULL,
    source_url TEXT,
    reviewed_by VARCHAR(200),
    reviewed_at TIMESTAMPTZ,
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING_REVIEW'
        CHECK (status IN ('PENDING_REVIEW', 'VERIFIED', 'REJECTED')),
    notes TEXT
);

CREATE TABLE facility (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    map_feature_id VARCHAR(80) NOT NULL UNIQUE REFERENCES map_feature(id),
    facility_type VARCHAR(80) NOT NULL,
    description TEXT,
    opening_hours TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(24) NOT NULL DEFAULT 'VISITOR'
        CHECK (role IN ('VISITOR', 'ADMIN', 'STAFF')),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE animal_discovery (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    animal_id BIGINT NOT NULL REFERENCES animal(id),
    discovered_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    xp_awarded INTEGER NOT NULL CHECK (xp_awarded >= 0),
    UNIQUE (user_id, animal_id)
);

CREATE TABLE visitor_progress (
    user_id BIGINT PRIMARY KEY REFERENCES app_user(id) ON DELETE CASCADE,
    total_xp BIGINT NOT NULL DEFAULT 0 CHECK (total_xp >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE achievement_badge (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    badge_key VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(160) NOT NULL,
    description TEXT NOT NULL,
    xp_threshold INTEGER CHECK (xp_threshold >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE visitor_badge (
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    badge_id BIGINT NOT NULL REFERENCES achievement_badge(id) ON DELETE CASCADE,
    awarded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, badge_id)
);

CREATE TABLE zoo_path (
    id VARCHAR(80) PRIMARY KEY REFERENCES map_feature(id),
    name VARCHAR(200) NOT NULL,
    geometry geometry(MultiLineString, 4326) NOT NULL,
    verification_status VARCHAR(24) NOT NULL DEFAULT 'UNVERIFIED'
        CHECK (verification_status IN ('UNVERIFIED', 'PENDING_REVIEW', 'VERIFIED')),
    active BOOLEAN NOT NULL DEFAULT FALSE,
    source_name VARCHAR(240),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT zoo_path_geometry_srid CHECK (ST_SRID(geometry) = 4326)
);

CREATE INDEX zoo_path_geometry_gix ON zoo_path USING GIST (geometry);
